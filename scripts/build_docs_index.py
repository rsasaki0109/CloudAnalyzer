#!/usr/bin/env python3
"""Write docs/README.md: a categorized index of every page under docs/.

Pages stay where they are, because docs/ is also the published Pages site and
existing links must keep working. The index groups guides first and collapses
the experiment and performance records. A page without a category lands in
"Other pages" until it is added to SECTIONS below.

    python scripts/build_docs_index.py           # rewrite docs/README.md
    python scripts/build_docs_index.py --check   # exit 1 when it is out of date
"""

from __future__ import annotations

import argparse
import fnmatch
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DOCS = REPO_ROOT / "docs"
INDEX = DOCS / "README.md"

# (title, patterns, collapsed). A page belongs to the first section it matches.
SECTIONS: list[tuple[str, list[str], bool]] = [
    ("Project", ["architecture", "interfaces", "decisions", "roadmap", "maturity", "ci",
                 "driver-plugin", "validation", "experiments", "mapping-priority-work", "release-*"], False),
    ("Tutorials", ["tutorial-*"], False),
    ("Point-cloud and survey workflows", [
        "browser-projects", "large-point-clouds", "map-coverage", "distance-regions",
        "surface-volume", "survey-change-review", "terrain-mesh", "point-map-applications",
        "copc-scale-validation"], False),
    ("Vector maps", ["vector-map-*"], False),
    ("SLAM experiments", ["slam-*"], True),
    ("CPU performance records", ["cpu-*", "c2c-real-source", "distance-summary"], True),
    ("GPU performance records", ["gpu-*"], True),
    ("WebAssembly performance records", ["wasm-*"], True),
]

HEADER = """# Documentation

<!-- Generated by scripts/build_docs_index.py; edit SECTIONS there, not this file. -->

Start with the [project README](../README.md), the
[browser guide](https://rsasaki0109.github.io/CloudAnalyzer/guide.html) and the
[command reference](commands/). Records below the guides keep the measurements
and decisions behind each change; they are collapsed because most readers only
need their conclusions.

## Lighter checkouts

The repository carries frozen benchmark evidence (`benchmarks/`, about 280 MB).
To work on the app, CLI or core without it, clone without blobs and leave that
directory out:

~~~sh
git clone --depth 1 --filter=blob:none --sparse https://github.com/rsasaki0109/CloudAnalyzer
cd CloudAnalyzer
git sparse-checkout set --no-cone '/*' '!/benchmarks/'
~~~

Measured on 2026-11-03, this downloads about 160 MB instead of about 570 MB for
a full shallow clone. Packet and benchmark tests need `benchmarks/`; run
`git sparse-checkout disable` before running them.
"""


def _title(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return path.stem


def render(docs: Path = DOCS) -> str:
    pages = sorted(p for p in docs.glob("*.md") if p.name != "README.md")
    grouped: dict[str, list[Path]] = {title: [] for title, _, _ in SECTIONS}
    other: list[Path] = []
    for page in pages:
        for title, patterns, _ in SECTIONS:
            if any(fnmatch.fnmatchcase(page.stem, p) for p in patterns):
                grouped[title].append(page)
                break
        else:
            other.append(page)
    parts = [HEADER]
    sections = [(t, grouped[t], collapsed) for t, _, collapsed in SECTIONS] + [("Other pages", other, False)]
    for title, entries, collapsed in sections:
        if not entries:
            continue
        lines = [f"- [{_title(p)}]({p.name})" for p in entries]
        if collapsed:
            parts.append(f"## {title}\n\n<details>\n<summary>{len(entries)} page{"s" if len(entries) != 1 else ""}</summary>\n\n"
                         + "\n".join(lines) + "\n\n</details>\n")
        else:
            parts.append(f"## {title}\n\n" + "\n".join(lines) + "\n")
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write the categorized docs index.")
    parser.add_argument("--check", action="store_true", help="Exit 1 if docs/README.md is out of date")
    args = parser.parse_args(argv)
    expected = render()
    if args.check:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current != expected:
            print("docs/README.md is out of date; run: python scripts/build_docs_index.py")
            return 1
        print("docs/README.md is up to date.")
        return 0
    INDEX.write_text(expected, encoding="utf-8")
    print(f"Wrote {INDEX.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
